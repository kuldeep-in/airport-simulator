"""SYSTEM B — the app's read loop. Polls Lakebase, broadcasts diffs to browsers.

This is the counterpart to the generator (server/simulator/broadcaster.py). The app
imports NO simulator module: everything it renders comes from three tables written by
the generator process.

    sim_positions   → aircraft (position, phase, gate, schedule, status)
    gate_occupancy  → gate status + current occupant
    sim_heartbeat   → is the generator alive? (else the UI would show frozen planes)

WHY POLL-AND-PUSH RATHER THAN LET BROWSERS POLL
-----------------------------------------------
One query per second serves EVERY connected browser, because the app fans the result
out over the existing WebSocket. If each browser polled Lakebase instead, load would
scale with viewers (N × poll rate) and latency would be worse (a poll lands at a random
offset within the tick, so it averages half an interval of staleness). Keeping the push
means the browser contract — and the whole frontend — is unchanged by the split.

A future upgrade is Postgres LISTEN/NOTIFY: the generator NOTIFYs after each tick and
this loop wakes on the signal instead of polling. Lakebase is real Postgres, so that
works; polling is just the simpler first step.

DIFFING
-------
The generator writes every live flight every tick, but browsers only need what CHANGED.
This loop keeps the last payload per flight and sends only differing ones, plus an
explicit `phase: "INACTIVE"` for flights whose row has disappeared (that's the frontend's
existing signal to delete an aircraft — see useSimStore.updateFlights).
"""

import asyncio
from datetime import datetime, timezone
from time import monotonic

from server.websocket_manager import manager
from server import airports
from server.simulator import positions
from server.simulator import gate_state
from server.simulator.zones import compute_zone_metrics
from server.simulator import seed as seed_mod
from server.simulator import sensor_gen

POLL_SECONDS = 1.0

# Fields that decide whether a flight's payload is worth re-sending. Position and phase
# change constantly; the descriptive fields (gate, status, runway) change rarely but
# must still propagate.
_DIFF_KEYS = ("lat", "lon", "heading", "phase", "ground_speed", "assigned_gate",
              "api_status", "runway", "gate_arrival")

_last_payload: dict[str, dict] = {}   # flight_id -> last payload sent
_zones: list = []
_feed_alive: bool | None = None       # last known generator liveness (to log transitions)

# Sensors are regenerated by the generator every 5 s. Polling at 2 s keeps the live
# view within ~2 s of each reading without re-reading on every 1 s position poll.
SENSOR_POLL_SECONDS = 2.0
_last_sensor_poll = 0.0
_last_sensor_sig: tuple | None = None   # last broadcast readings, to skip no-op pushes


def sim_state() -> dict:
    """The clock the frontend uses for countdowns. The generator pins its sim clock to
    real UTC, so the app can simply report `now()` — it doesn't need to be told. Speed
    is fixed at 1x and pausing is gone: with two independent systems the app cannot
    pause the generator, and pretending otherwise would be a lie in the UI."""
    return {
        "speed": 1,
        "paused": False,
        "sim_time": datetime.now(timezone.utc).isoformat(),
    }


def _zone_payload() -> dict:
    """Zone metrics for the heatmap. `compute_zone_metrics` is a pure function of
    sim_time, so the app derives identical values to the generator without shipping
    them through a table (the generator still persists them for history)."""
    global _zones
    if not _zones:
        _zones = seed_mod.load_zones_geojson()
    out: dict = {}
    for m in compute_zone_metrics(_zones, datetime.now(timezone.utc)):
        out.setdefault(m["zone_id"], {})[m["metric_type"]] = m["value"]
    return out


def _changed(fid: str, payload: dict) -> bool:
    prev = _last_payload.get(fid)
    if prev is None:
        return True
    return any(prev.get(k) != payload.get(k) for k in _DIFF_KEYS)


async def build_full_state() -> dict:
    """Full snapshot for a newly-connected browser and GET /api/state — read entirely
    from Lakebase. `feed` reports generator liveness so the UI can distinguish a quiet
    airport from a dead generator."""
    rows = await positions.fetch_for_airport(airports.IATA)
    flights_out = [positions.to_payload(r) for r in rows]
    positions_out = {
        f["id"]: {
            "flight_id":    f["id"],
            "lat":          f["lat"],
            "lon":          f["lon"],
            "heading":      f["heading"],
            "ground_speed": f["ground_speed"],
            "phase":        f["phase"],
        }
        for f in flights_out
    }
    return {
        "type":      "full_state",
        "flights":   flights_out,
        "gates":     await gate_state.fetch_snapshot(),
        "positions": positions_out,
        "zones":     _zone_payload(),
        "sensors":   await sensor_gen.get_current(),
        "feed":      await positions.feed_status(),
        **sim_state(),
    }


async def run_loop() -> None:
    """Poll Lakebase once a second; broadcast only what changed."""
    global _feed_alive
    print("[reader] started — polling Lakebase for generator output")
    while True:
        try:
            rows = await positions.fetch_for_airport(airports.IATA)
            payloads = {r["flight_id"]: positions.to_payload(r) for r in rows}

            changed = [p for fid, p in payloads.items() if _changed(fid, p)]

            # A flight whose row vanished has left the map. `phase: INACTIVE` is the
            # frontend's existing delete signal, so no frontend change was needed.
            gone = [fid for fid in _last_payload if fid not in payloads]
            for fid in gone:
                changed.append({"id": fid, "callsign": _last_payload[fid].get("callsign"),
                                "phase": "INACTIVE", "source": "lakebase"})

            _last_payload.clear()
            _last_payload.update(payloads)

            if changed:
                await manager.broadcast({"type": "aircraft_update", "flights": changed})
            await manager.broadcast({"type": "zone_metric", "zones": _zone_payload()})
            await manager.broadcast({"type": "sim_tick", **sim_state()})

            # Sensor readings (temperature + pax density) are written to Lakebase by the
            # generator every 5 s. The APP has to push them: sensor_gen used to
            # broadcast directly, which stopped reaching browsers when the generator
            # became a separate process (it has no WebSocket clients), leaving the
            # heatmap frozen on whatever the initial snapshot contained.
            global _last_sensor_poll, _last_sensor_sig
            nowm = monotonic()
            if nowm - _last_sensor_poll >= SENSOR_POLL_SECONDS:
                _last_sensor_poll = nowm
                sensors = await sensor_gen.get_current()
                sig = tuple((s["sensor_id"], s["temperature"], s["pax_density"])
                            for s in sensors)
                if sensors and sig != _last_sensor_sig:
                    _last_sensor_sig = sig
                    await manager.broadcast({"type": "sensor_update", "sensors": sensors})

            # Log generator liveness transitions once, rather than every second.
            feed = await positions.feed_status()
            if feed.get("alive") != _feed_alive:
                _feed_alive = feed.get("alive")
                print(f"[reader] generator feed "
                      f"{'ALIVE' if _feed_alive else 'STALE/DOWN'} "
                      f"(heartbeat age={feed.get('age_seconds')}s)")
        except Exception as e:  # noqa: BLE001
            print(f"[reader] poll error: {e}")
        await asyncio.sleep(POLL_SECONDS)
